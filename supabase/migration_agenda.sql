-- أجندة المشرفين: مهام ومواعيد تخطيط العمل
create table if not exists mharaty.agenda_items (
  id bigint generated by default as identity primary key,
  title text not null,
  notes text,
  item_date date not null,
  item_time text,
  kind text not null default 'task' check (kind in ('task','meeting','deadline','other')),
  is_done boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists agenda_items_date_idx on mharaty.agenda_items (item_date);
alter table mharaty.agenda_items enable row level security;
drop policy if exists "admin manage" on mharaty.agenda_items;
create policy "admin manage" on mharaty.agenda_items for all to authenticated using (true) with check (true);
grant select, insert, update, delete on mharaty.agenda_items to authenticated;
grant usage, select on all sequences in schema mharaty to authenticated;
